"""Build the GitHub wiki pages in work/wiki from the repo's own sources.

    python -I tools/wiki_build.py [--out work/wiki]

Sources (one place each, so the wiki never drifts from them):
  docs/wiki/*.md                                the hand-written findings pages and Home
  .claude/skills/mlbts-game-code/SKILL.md       -> Start-here
  .claude/skills/mlbts-game-code/references/*   -> How-the-port-works, The-game-binary, Known-game-functions,
                                                   Tracing-playbook, History-and-open-questions
  docs/map/regions/*.md                         -> Region-A ... Region-F
  docs/map/README.md                            -> Tools-and-the-code-map
Skill and map pages are generated: edit the source, not the wiki page. Wiki pages carry no front matter and no top
heading (GitHub shows the page name), and links between pages use the wiki's own page names.
Publishing is separate and manual (see the wiki section of `.claude/skills/mlbts-game-code/SKILL.md`): this script
only writes files.
"""
import argparse, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace("\\", "/")
SK = ROOT + "/.claude/skills/mlbts-game-code"

SKILL_PAGES = {
    "SKILL.md": "Start-here",
    "references/port-architecture.md": "How-the-port-works",
    "references/game-binary.md": "The-game-binary",
    "references/known-functions.md": "Known-game-functions",
    "references/tracing-playbook.md": "Tracing-playbook",
    "references/history-and-open-questions.md": "History-and-open-questions",
}
LINKS = {  # text in the source -> wiki page
    "references/port-architecture.md": "How-the-port-works",
    "references/game-binary.md": "The-game-binary",
    "references/known-functions.md": "Known-game-functions",
    "references/tracing-playbook.md": "Tracing-playbook",
    "references/history-and-open-questions.md": "History-and-open-questions",
    "known-functions.md": "Known-game-functions",
    "game-binary.md": "The-game-binary",
    "port-architecture.md": "How-the-port-works",
    "tracing-playbook.md": "Tracing-playbook",
}
REGIONS = {"A": "A-0x7000000000-0x70005fffff", "B": "B-0x7000600000-0x7000bfffff", "C": "C-0x7000c00000-0x7000ffffff",
           "D": "D-0x7001000000-0x70013fffff", "E": "E-0x7001400000-0x70017fffff", "F": "F-0x7001800000-end-and-sdk"}
BANNER = ("_Generated by `tools/wiki_build.py` from `%s` in the repo. The page is rewritten on every build._\n\n")


def read(p):
    return open(p, encoding="utf-8").read()


def strip_front_and_title(t):
    t = re.sub(r"\A---\n.*?\n---\n", "", t, flags=re.S)
    return re.sub(r"\A\s*# [^\n]*\n+", "", t)


def relink(t):
    for src, page in sorted(LINKS.items(), key=lambda kv: -len(kv[0])):
        t = t.replace(f"`{src}`", f"[{page.replace('-', ' ')}]({page})")
    t = re.sub(r"`?docs/map/regions/\*\.md`?(?: \(A to F\))?", "the region pages ([A](Region-A), [B](Region-B), [C](Region-C), "
               "[D](Region-D), [E](Region-E), [F](Region-F))", t)
    t = re.sub(r"`docs/map/regions/([A-F])-[^`]*`", lambda m: f"[Region {m.group(1)}](Region-{m.group(1)})", t)
    t = re.sub(r"`docs/map/README\.md`[^|\n]*", "[Tools and the code map](Tools-and-the-code-map)", t)
    return t


def write(out, name, body, source):
    open(f"{out}/{name}.md", "w", encoding="utf-8", newline="\n").write((BANNER % source if source else "") + body.strip() + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=ROOT + "/work/wiki")
    a = ap.parse_args()
    shutil.rmtree(a.out, ignore_errors=True)
    os.makedirs(a.out)
    pages = []
    for f in sorted(os.listdir(ROOT + "/docs/wiki")):
        if f.endswith(".md"):
            shutil.copy(f"{ROOT}/docs/wiki/{f}", f"{a.out}/{f}")
            pages.append(f[:-3])
    for src, page in SKILL_PAGES.items():
        body = relink(strip_front_and_title(read(f"{SK}/{src}")))
        write(a.out, page, body, f".claude/skills/mlbts-game-code/{src}")
        pages.append(page)
    for letter, stem in REGIONS.items():
        body = relink(strip_front_and_title(read(f"{ROOT}/docs/map/regions/{stem}.md")))
        body += (f"\nEvery function in this range that carries a symbol, an import or a string is listed on "
                 f"[Functions {letter}](Functions-{letter}); the ones with no string or symbol are counted there by "
                 f"shape and on [Function census](Function-census).\n")
        write(a.out, f"Region-{letter}", body, f"docs/map/regions/{stem}.md")
        pages.append(f"Region-{letter}")
    bodies = {"intro-states": "Intro-states", "batter-up": "Batter-up-state", "pre-play-in-play": "Play-states",
              "play-inning-game-over": "End-states", "fielding": "Fielding", "frontend": "Frontend",
              "audio": "Audio", "ai-layer": "AI-actor-API", "lighting": "Lighting", "modes": "Game-modes"}
    for stem, page in bodies.items():
        body = relink(strip_front_and_title(read(f"{ROOT}/docs/map/bodies/{stem}.md")))
        write(a.out, page, body, f"docs/map/bodies/{stem}.md")
        pages.append(page)
    readme = relink(strip_front_and_title(read(ROOT + "/docs/map/README.md")))
    readme = re.sub(r"\[(source/[^\]]+)\]\([^)]*\)", r"`docs/map/\1`", readme)
    readme = readme.replace("[coverage.md](coverage.md)", "`docs/map/coverage.md`").replace("[binary.md](binary.md)", "[The game binary](The-game-binary)")
    readme = re.sub(r"\[regions/\]\(regions/\)", "the region pages", readme)
    readme = re.sub(r"\[bodies/\]\(bodies/\)", "the game flow pages", readme)
    write(a.out, "Tools-and-the-code-map", readme, "docs/map/README.md")
    pages.append("Tools-and-the-code-map")
    # the complete function map: built from work/map/index/roles.jsonl (tools/map_roles.py), not from a committed source
    sys.path.insert(0, ROOT + "/tools")
    import map_functions_doc
    fpages = map_functions_doc.pages_for(ROOT + "/work/map/index", a.out)
    pages.extend(fpages)
    fm = ["Function-map", "Function-census", "Functions-A", "Functions-B", "Functions-C", "Functions-D", "Functions-E",
          "Functions-F", "Functions-SDK"]
    if "Read-roles" in pages:
        fm.append("Read-roles")
    if "Class-fields" in pages:
        fm.append("Class-fields")
    if "Save-schema" in pages:
        fm.append("Save-schema")
    if "Theming-progress" in pages:
        fm.append("Theming-progress")
    sections = [
        ("How the port works", ("How-the-port-works", "The-game-binary", "Known-game-functions", "Tracing-playbook",
                                "Dev-harness-and-measuring")),
        ("Game flow", ("Game-state-machine", "Intro-states", "Batter-up-state", "Play-states", "End-states")),
        ("Subsystems", ("Fielding", "Frontend", "Audio", "AI-actor-API", "Lighting", "Game-modes")),
        ("Function map", tuple(fm)),
        ("Game binary regions", tuple(f"Region-{l}" for l in REGIONS)),
        ("Findings", ("Walk-up-freeze", "Match-start-freeze", "Load-stalls", "Frame-rate-and-GPU-waits",
                      "PS5-textures", "Upstream-bug-research")),
        ("Reference", ("History-and-open-questions", "Tools-and-the-code-map", "Start-here")),
    ]

    # the function-register pages are named by the address range they cover, not by a letter: a reader looking for
    # 0x7001200000 should not have to work out which letter holds it
    ranges = {f"Functions-{k}": (lo, hi) for k, lo, hi in map_functions_doc.REGIONS}
    ranges["Functions-SDK"] = map_functions_doc.SDK
    for k, lo, hi in map_functions_doc.REGIONS:
        ranges[f"Region-{k}"] = (lo, hi)

    def label(p):
        if p in ranges:
            lo, hi = ranges[p]
            return f"0x{lo:x}-0x{hi - 1:x}"
        return p.replace("-", " ")

    def numbered(p):
        return p.startswith("Functions-") or p.startswith("Region-")

    side = ["[Home](Home)"]
    for title, ps in sections:
        side += ["", title] + [f"{'1.' if numbered(p) else '-'} [{label(p)}]({p})" for p in ps]
    open(f"{a.out}/_Sidebar.md", "w", encoding="utf-8", newline="\n").write("\n".join(side) + "\n")
    # the home page's table of contents: every page, grouped the way the sidebar groups it, from the same lists. The
    # read-role detail pages are generated in bulk and kept off the sidebar; the table lists them too, so no page is
    # reachable only through another page.
    toc = ["| Section | Pages |", "|---|---|"]
    for title, ps in sections:
        toc.append(f"| {title} | " + " \u00b7 ".join(f"[{label(p)}]({p})" for p in ps) + " |")
    listed = {p for _, ps in sections for p in ps}
    read_rest = sorted(p for p in pages if p not in listed and re.match(r"Read-[A-F]-\d+$", p))
    other = sorted(p for p in pages if p not in listed and p not in read_rest and p != "Home")
    if read_rest:
        toc.append("| Read roles detail | " + " \u00b7 ".join(f"[Read {p[5:]}]({p})" for p in read_rest) + " |")
    if other:
        toc.append("| Other pages | " + " \u00b7 ".join(f"[{label(p)}]({p})" for p in other) + " |")
    # the charts: coverage and window aspects from the index, theme-label progress from tools/data/theming-pilot.json.
    # Names carry a content hash, because GitHub serves wiki images from a cache keyed by URL. Every page may carry a
    # {{name.svg}} placeholder; the pages themselves carry the same counts in text.
    if os.path.exists(ROOT + "/work/map/index/roles.jsonl"):
        import wiki_completeness
        names, *_ = wiki_completeness.write(ROOT + "/work/map/index", a.out)
        import wiki_theming
        names.update(wiki_theming.write(a.out))
        for page in os.listdir(a.out):
            if not page.endswith(".md"):
                continue
            path = f"{a.out}/{page}"
            t = read(path)
            for kind, name in names.items():
                t = t.replace("{{" + kind + ".svg}}", name)
            open(path, "w", encoding="utf-8", newline="\n").write(t)
    for page in os.listdir(a.out):
        if not page.endswith(".md"):
            continue
        path = f"{a.out}/{page}"
        t = read(path)
        if "{{toc}}" in t:
            open(path, "w", encoding="utf-8", newline="\n").write(t.replace("{{toc}}", "\n".join(toc)))
    missing = [p for p in pages if not os.path.exists(f"{a.out}/{p}.md")]
    print(f"{len(pages)} pages written to {a.out}; missing: {missing}")
    # every [text](Page) link must point at a page we wrote
    names = set(pages) | {"Home"}
    bad = []
    for p in pages:
        for m in re.finditer(r"\]\(([A-Za-z0-9-]+)\)", read(f"{a.out}/{p}.md")):
            if m.group(1) not in names:
                bad.append((p, m.group(1)))
    print("broken wiki links:", bad[:10] or "none")
    # house rule: table column headers are one to three words, one preferred
    long_hdr = []
    for p in pages:
        L = read(f"{a.out}/{p}.md").split("\n")
        for i, line in enumerate(L[:-1]):
            if line.startswith("|") and re.match(r"^\|[\s:|-]+\|?\s*$", L[i + 1]) and "---" in L[i + 1]:
                for c in [c.strip() for c in line.strip().strip("|").split("|")]:
                    if len(c.replace("`", "").split()) > 3 or not c:
                        long_hdr.append((p, c))
    print("table headers over three words or empty:", long_hdr[:10] or "none")
    if bad or long_hdr:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
