"""Write docs/map/ from the function indexes (tools/map_source.py, map_generated.py, map_binary.py).

    python -I tools/map_docs.py [--index work/map/index] [--out docs/map]

docs/map/source/<area>.md   every hand-written/vendored function: file, line range, signature, direct callees, and the
                            comment or docstring directly above it as its purpose (blank when there is none).
docs/map/binary.md          the game binary (modules main and sdk) as aggregates: address ranges, function counts per
                            generated chunk, SDK namespaces from the dynamic symbols, and every function the repo's
                            docs or code already names by address. The per-function list is derived from game code,
                            so it stays in work/map/ and is not committed; rebuild it with the three map_*.py tools.
"""
import argparse, json, os, re, subprocess
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))).replace("\\", "/")


def esc(s, n=140):
    s = " ".join(str(s).split()).replace("|", "\\|")
    return s if len(s) <= n else s[:n - 1] + "…"


def comment_above(lines, line):
    i, out = line - 2, []
    while i >= 0:
        t = lines[i].strip()
        if t.startswith("//") or t.startswith("*") or t.startswith("/*") or t.endswith("*/"):
            out.append(t.lstrip("/*# ").rstrip("*/ ").strip())
            i -= 1
        elif t.startswith("#") and not t.startswith("#if") and not t.startswith("#define") and \
                not t.startswith("#include") and not t.startswith("#endif") and not t.startswith("#else"):
            out.append(t.lstrip("# "))
            i -= 1
        else:
            break
    return " ".join(x for x in reversed(out) if x)


def slug(area):
    return area.replace("/", "-")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", default=ROOT + "/work/map/index")
    ap.add_argument("--out", default=ROOT + "/docs/map")
    a = ap.parse_args()
    src = [json.loads(l) for l in open(a.index + "/source_functions.jsonl", encoding="utf-8")]
    os.makedirs(a.out + "/source", exist_ok=True)
    for fn in os.listdir(a.out + "/source"):
        os.remove(a.out + "/source/" + fn)
    by_area = defaultdict(lambda: defaultdict(list))
    for f in src:
        by_area[f["area"]][f["file"]].append(f)
    cache = {}
    for area, files in sorted(by_area.items()):
        out = [f"# Functions in `{area}`", "",
               f"{sum(len(v) for v in files.values())} functions in {len(files)} files. Generated by "
               "`tools/map_docs.py`; do not edit. Purpose is the comment or docstring directly above the "
               "definition, blank when there is none. Calls lists direct callees by name (functions only).", ""]
        vend = area in ("tools/vendor", "runtime/third_party")
        for file, fs in sorted(files.items()):
            if file not in cache:
                cache[file] = open(ROOT + "/" + file, encoding="utf-8", errors="replace").read().split("\n")
            out += [f"## `{file}`", "", "| Function | Lines | Signature | Calls | Purpose |", "|---|---|---|---|---|"]
            for f in fs:
                purpose = f["signature"] if f["parser"] == "ast" else \
                    ("" if vend else esc(comment_above(cache[file], f["line"]), 200))
                sig = "" if f["parser"] == "ast" else esc(f["signature"], 90)
                calls = ", ".join(f["calls"][:8]) + (f" (+{len(f['calls']) - 8})" if len(f["calls"]) > 8 else "")
                rng = f"{f['line']}-{f['end']}" if f["end"] != f["line"] else str(f["line"])
                st = f"{f['storage']} " if f["storage"] in ("static",) else ""
                out.append(f"| `{f['name']}` | {rng} | {st}{sig} | {esc(calls, 120)} | {esc(purpose, 200)} |")
            out.append("")
        open(f"{a.out}/source/{slug(area)}.md", "w", encoding="utf-8", newline="\n").write("\n".join(out))

    gen = [json.loads(l) for l in open(a.index + "/generated_functions.jsonl")]
    gsum = json.load(open(a.index + "/generated_summary.json"))
    bchk = json.load(open(a.index + "/binary_check.json"))
    names = [json.loads(l) for l in open(a.index + "/binary_names.jsonl", encoding="utf-8")]
    by_addr = {int(f["addr"], 16): f for f in gen}
    chunks = defaultdict(list)
    for f in gen:
        chunks[f["file"]].append(f)
    ns = Counter()
    for n in names:
        if n["module"] == "sdk":
            d = n["demangled"]
            ns["::".join(d.split("(")[0].split("::")[:2]) if "::" in d else "(C or unscoped)"] += 1
    tracked = subprocess.run(["git", "-C", ROOT, "ls-files", "-co", "--exclude-standard"], capture_output=True,
                             text=True).stdout.split("\n")
    pat = re.compile(r"\bf_(7[0-9a-f]{9})\b")
    known = defaultdict(list)
    for t in tracked:
        if not t or t.startswith(".claude/") or t.startswith("tools/vendor") or not t.endswith(
                (".md", ".c", ".h", ".cpp", ".py", ".txt")):
            continue
        try:
            for ln, line in enumerate(open(ROOT + "/" + t, encoding="utf-8", errors="replace"), 1):
                for m in pat.finditer(line):
                    known[int(m.group(1), 16)].append((t, ln, " ".join(line.split())))
        except OSError:
            pass
    o = ["# The game binary (Switch 1.0.20)", "",
         "The port recompiles the game's ARM64 code to C (`recomp/gen.py`). Each recompiled function is "
         "`void f_<address>(Cpu *c)`, and `<address>` is its virtual address in the original module "
         "(`main` at `0x7000000000`, `sdk` at `0x7004c00000`). This page holds counts, address ranges and the "
         "functions the repo already names. The full per-function list (address, size, direct callees, caller "
         "count, indirect-branch count, SDK symbol name) is derived from game code, so it is built locally into "
         "`work/map/index/` by `tools/map_generated.py` and `tools/map_binary.py` and is not committed. "
         "`rtld` (8.5 KB) is not recompiled.", "",
         "## Totals", "", "| Module | Functions | Text range | Generated lines | Chunks |", "|---|---|---|---|---|"]
    for mod in ("main", "sdk"):
        m = gsum[mod]
        o.append(f"| {mod} | {m['indexed']} | {m['text'][0]} - {m['text'][1]} | {m['generated_lines']} | "
                 f"{m['chunks']} |")
    o += ["", f"Total {gsum['total_indexed']} functions; {gsum['uncalled_functions']} have no direct caller "
          "(called through tables, `rt_dispatch`, or exported); "
          f"{gsum['with_indirect_dispatch']} contain at least one indirect branch (`rt_dispatch`).", "",
          "## Independent check against the original machine code", "",
          "`tools/map_binary.py` scans the original `.text` for every direct `bl` and requires each target to be an "
          "indexed function.", "", "| Module | bl instructions | distinct targets | not indexed | named symbols | not indexed |",
          "|---|---|---|---|---|---|"]
    for mod in ("main", "sdk"):
        m = bchk[mod]
        o.append(f"| {mod} | {m['bl_instructions_scanned']} | {m['distinct_bl_targets_in_text']} | "
                 f"{m['bl_targets_not_indexed']} | {m['named_function_symbols']} | {m['named_symbols_not_indexed']} |")
    o += ["", "## Address ranges by generated chunk", "",
          "| Chunk | Functions | First address | Last address | Generated lines |", "|---|---|---|---|---|"]
    for ck, fs in sorted(chunks.items()):
        ad = sorted(int(f["addr"], 16) for f in fs)
        o.append(f"| `{ck}` | {len(fs)} | {hex(ad[0])} | {hex(ad[-1])} | {sum(f['lines'] for f in fs)} |")
    o += ["", "## SDK namespaces (from the `sdk` module's named symbols)", "",
          f"{sum(1 for n in names if n['module'] == 'sdk')} named functions. Top namespaces by count:", "",
          "| Namespace | Named functions |", "|---|---|"]
    for k, v in ns.most_common(60):
        o.append(f"| `{esc(k, 60)}` | {v} |")
    o += ["", f"{len(ns) - 60 if len(ns) > 60 else 0} more namespaces not shown.", "",
          "## `main` module named symbols", "", "| Address | Symbol |", "|---|---|"]
    for n in names:
        if n["module"] == "main":
            o.append(f"| {n['addr']} | `{esc(n['demangled'], 100)}` |")
    o += ["", "## Functions the repo already names by address", "",
          "Every `f_70…` address that appears in a doc, source file or script, with what the line says. "
          "Callers, callees and size come from the index.", "",
          "| Address | Callers | Direct callees | Lines | Mentioned in | Context |", "|---|---|---|---|---|---|"]
    for ad in sorted(known):
        f = by_addr.get(ad)
        st = f"{f['callers']} | {len(f['calls'])} | {f['lines']}" if f else "? | ? | ?"
        t, ln, ctx = known[ad][0]
        extra = f" (+{len(known[ad]) - 1} more)" if len(known[ad]) > 1 else ""
        o.append(f"| {hex(ad)} | {st} | `{t}:{ln}`{extra} | {esc(ctx, 130)} |")
    open(a.out + "/binary.md", "w", encoding="utf-8", newline="\n").write("\n".join(o) + "\n")

    idx = ["# Codebase map", "",
           "A function-level map of this repo and the game binary it runs. Built by scripts in `tools/`, so it can "
           "be regenerated and checked.", "",
           "## Rebuild", "",
           "```", "python -I -m pip install libclang --target work/pylib      # once; libclang for the C/C++ parse",
           "python -I tools/map_source.py --out work/map/index                # hand-written and vendored source",
           "python -I tools/map_generated.py                                  # recompiled game code (needs work/gen)",
           "python -I tools/map_binary.py                                     # names + check vs the original code",
           "python -I tools/map_strings.py                                    # strings per game function + vtables",
           "python -I tools/map_all.py                                        # all of the above in order, then docs + coverage",
           "python -I tools/map_find.py fn 0x700108b628                       # look up a game function (see its docstring)",
           "python -I tools/map_docs.py                                       # writes docs/map/",
           "python -I tools/map_coverage.py                                   # exits 1 if anything is unmapped", "```",
           "", "See [coverage.md](coverage.md) for the last result.", "",
           "## Repo contents", "", "| Area | Functions | Page |", "|---|---|---|"]
    for area in sorted(by_area):
        idx.append(f"| `{area}` | {sum(len(v) for v in by_area[area].values())} | [source/{slug(area)}.md]"
                   f"(source/{slug(area)}.md) |")
    idx += ["", f"Total: {len(src)} source functions. C/C++ come from a libclang parse (a real compiler front end, "
            "same defines and include paths as the build), Python from `ast`, vendored C# and GLSL from a regex "
            "(lower fidelity).", "",
            "## Game binary", "", "See [binary.md](binary.md): 135,060 recompiled functions in the `main` and "
            "`sdk` modules, address ranges, SDK namespaces and the functions the repo already names.", "",
            '[regions/](regions/) holds one note per address range of `main` (A to F, with the `sdk` module in F): subsystem per 256 KB window and key functions, every claim tagged confirmed, inferred or guess.', "",
            '[bodies/](bodies/) holds notes from reading function bodies (the 12 game-state classes and six subsystem passes), each report spot-checked against the generated C. The `.claude/skills/mlbts-game-code` skill is the entry point for future sessions.', "",
            'A complete function map is generated from the same index:', "",
            '- [Function map](Function-map) has the method and the totals.\n- [Function census](Function-census) counts every function in every 256 KB window.\n- `Functions-A` to `Functions-F` plus `Functions-SDK` list every function that carries a symbol, an import or a string.', "",
            '`tools/map_roles.py` names the import thunks from the relocation table and classifies every body; `tools/map_functions_doc.py` writes the pages. Both read `work/map/index/`, so those pages are rebuilt locally like the index and are not committed.', "",
            'The functions with no string, symbol or simple shape are read from their own code:', "",
            '1. `tools/map_read_prep.py` normalises each generated body to its meaningful operations and writes dossiers in batches.\n2. Subagents read the batches and write `out-<n>.jsonl`.\n3. `tools/map_read_merge.py` validates them into `work/map/index/roles_read.jsonl`.\n4. `tools/map_roles.py` applies that overlay, so the census and the `Read roles` pages carry what the read found.', "",
            'That pass covered 47,308 `main` functions; the completeness pass reads every remaining body, `sdk` included (see [read-pass.md](read-pass.md)).', "",
            "The game's saves carry their own class and field names. `tools/save_schema.py` reads that schema out of "
            "the zlib-compressed Flux archive in a save and writes `work/map/saves/schema.json`; the wiki's "
            "`Save schema` page lists the classes and fields, and searching one of those names in the code finds the "
            "function that reads or writes it.", "",
            "## Subsystems", "", "| Area | What it is |", "|---|---|",
            "| `runtime/core` | Generic Switch-OS host: CPU state, memory, kernel services, audio, filesystem |",
            "| `runtime/gfx` | NVN-to-Vulkan graphics layer, shader handling, textures, upscalers, UI |",
            "| `runtime/mlb` | MLB-specific hooks: input, saves, resolution, dev harness |",
            "| `runtime/shaders` | Shader sources |",
            "| `runtime/third_party` | Vendored Dear ImGui and AMD FidelityFX headers |",
            "| `recomp` | Recompiler: ARM64 lifter and C emitter (`gen.py`) |",
            "| `installer` | Setup and updater |",
            "| `tools` | Build, dev harness, test and analysis scripts |",
            "| `tools/xlate`, `tools/vendor` | Shader translator built on vendored Ryujinx C# |",
            "| `tools/packages`, `tools/equipment` | Offline package and equipment tooling |", ""]
    open(a.out + "/README.md", "w", encoding="utf-8", newline="\n").write("\n".join(idx))
    print("docs written:", len(src), "source functions,", len(gen), "binary functions,", len(known), "named addresses")


if __name__ == "__main__":
    main()
