def sdk_page(rows):
    sdk = [r for r in rows if r["module"] == "sdk"]
    c = Counter(r["tag"] for r in sdk)
    out = [f"The `sdk` module holds {len(sdk):,} functions between `0x{SDK[0]:x}` and `0x{SDK[1] - 1:x}`: Nintendo's SDK "
           f"(19.3.11) plus the NVN graphics driver. {c['C']:,} carry evidence, {c['I']:,} an inferred role and "
           f"{c['H']:,} only a caller or a shape. The 18,299 named functions are named by the SDK's own symbol table; "
           f"the 7,961 import thunks are named by the relocation that fills their slot; the rest are unnamed.", ""]
    ns = Counter()
    nrange = {}
    for r in sdk:
        if r["kind"] == "sdk" and r["name"]:
            n = r["name"]
            if n.startswith("nn::"):
                key = "::".join(n.split("::")[:2])
            elif n.startswith(("std::", "__", "operator")) or "::" not in n:
                key = "C++ runtime and libc"
            else:
                key = n.split("::")[0] or "other"
            ns[key] += 1
            a = int(r["addr"], 16)
            lo, hi = nrange.get(key, (a, a))
            nrange[key] = (min(lo, a), max(hi, a))
    imports = [r for r in sdk if r["kind"] == "import"]

    def group_of(n):
        if n.startswith(("std::", "operator", "__cxa", "__cxx")):
            return "C++ runtime"
        if n.startswith("nn::"):
            return "::".join(n.split("::")[:2])
        return "libc and others"
    groups = Counter()
    examples = defaultdict(list)
    for r in imports:
        g = group_of(r["name"])
        groups[g] += 1
        if len(examples[g]) < 2 and r["name"] not in examples[g]:
            examples[g].append(r["name"])
    out += ["## Import thunks", "",
            "A thunk loads a pointer from the SDK's import table and jumps through it. The SDK has 7,961 of them, one "
            "per imported symbol. They are grouped by the library the symbol belongs to; the local index has the "
            "exact name for each (`python -I tools/map_find.py role 0xADDR`).", "",
            table(["Group", "Thunks", "Examples"],
                  [[g, n, "; ".join(examples[g])] for g, n in groups.most_common()]), ""]
    out += ["## Named by namespace", "",
            "Every named SDK function is in the local index with its demangled symbol (`tools/map_find.py name nvnQueue`). "
            "The table groups them by namespace, which is what the port's own code uses to see what the game asks of "
            "the OS.", "",
            table(["Namespace", "Functions", "First", "Last"],
                  [[k, v, hex(nrange[k][0]), hex(nrange[k][1])] for k, v in ns.most_common()]), ""]
    sh = Counter(r["shape"] for r in sdk if r["kind"] == "boilerplate")
    out += ["## Unnamed functions by shape", "",
            table(["Shape", "Count", "Meaning"], [[s, n, SHAPES.get(s, s)] for s, n in sh.most_common()]), "",
            "The windows and counts for the whole module are on [Function census](Function-census)."]
    return "\n".join(out)


def fields_page(limit=80):
    """Per class (vtable), the this-relative fields its methods use, with the readable roles that touch them."""
    path = f"{ROOT}/work/map/fields/classes.jsonl"
    if not os.path.exists(path):
        return {}
    classes = [json.loads(l) for l in open(path, encoding="utf-8")]
    # keep class-sized groups: a real class has a handful to a few dozen fields and slots; the very large groups are
    # dispatch tables whose x0 is an argument, not `this`
    classes = [c for c in classes if 6 <= len(c["fields"]) <= 80 and c["size"] <= 64
               and max(f[3] for f in c["fields"]) <= 40]
    classes.sort(key=lambda c: -len(c["fields"]))
    GENERIC = ("calls through a table", "virtual slot", "empty stub", "helper", "returns a constant",
               "helper: calls", "no caller")
    out = ["Every class here is identified by its vtable; the rows are the offsets its own methods read and write "
           "through `this` (x0). Built by `tools/map_fields.py` from the generated C plus the function roles; offsets "
           "are 1.0.20.", "",
           legend("Offset is the this-relative byte offset. R/W says whether the field is read or written. Uses "
                  "counts the accesses found. Users names up to two functions that touch it, in plain words, so a "
                  "field can be recognised before its meaning is known. A `-` means only generic code uses it."), "",
           "The vtable-to-class link is provisional: the index finds tables of function pointers, and some are "
           "dispatch tables for several classes, so a group whose slots read unrelated things is probably not a "
           "class. Very large groups (150+ fields) and groups with no clear shape are left out.", "",
           "## Classes on this page", "",
           table(["Vtable", "Slots", "Fields"],
                 [[c["vtable"], c["size"], len(c["fields"])] for c in classes[:limit]]), "",
           "The field table of each class follows.", ""]
    for c in classes[:limit]:
        rows = []
        for off, w, rw, n, who in c["fields"][:25]:
            users = [f"{u[1]} [{u[2]}]" for u in who if not u[1].startswith(GENERIC)]
            rows.append([hex(off), w, rw, f"{n}", "; ".join(users[:2]) or "-"])
        out.append(details(f"{c['vtable']} · {c['size']} slots · {len(c['fields'])} fields",
                           table(["Offset", "Bytes", "R/W", "Uses", "Users"], rows)))
    out.append("Classes are ordered by how many fields their methods touch. A field's meaning still has to be "
               "confirmed against the game; this page answers which code reads and writes it, not what it stores.")
    return {"Class-fields": "\n".join(out)}


def pages_for(index, out):
    """Write the function-map pages into `out`; return their wiki page names (used by tools/wiki_build.py)."""
    rows = load(index)
    os.makedirs(out, exist_ok=True)
    pages = {"Function-map": overview(rows, json.load(open(f"{index}/roles_summary.json"))),
             "Function-census": census(rows)}
    for letter, lo, hi in REGIONS:
        pages[f"Functions-{letter}"] = register(rows, letter)
    pages["Functions-SDK"] = sdk_page(rows)
    pages.update(read_pages(rows))
    pages.update(fields_page())
    pages.update(save_schema_page())
    for name, body in pages.items():
        open(f"{out}/{name}.md", "w", encoding="utf-8", newline="\n").write(BANNER + body.strip() + "\n")
    return sorted(pages)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--index", default=ROOT + "/work/map/index")
    ap.add_argument("--out", default=ROOT + "/work/wiki")
    a = ap.parse_args()
    names = pages_for(a.index, a.out)
    print(f"{len(names)} function pages written to {a.out}: {', '.join(names)}")


if __name__ == "__main__":
    main()
