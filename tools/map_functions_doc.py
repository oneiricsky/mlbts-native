def read_pages(rows, limit=3500):
    """Pages for the functions whose role was read from the body (the overlay). Chunked so no page is unreadable."""
    read = sorted([r for r in rows if r.get("read")], key=lambda r: int(r["addr"], 16))
    if not read:
        return {}
    pages, index = {}, ["These are the functions of `main` whose role was read from their own code, in address order. "
                        "The evidence for each row is in `work/map/index/roles_read.jsonl`; the per-region register "
                        "on [Functions A](Functions-A) to [Functions F](Functions-F) lists the ones with a symbol, "
                        "import or string.", "",
                        "These roles are unverified. They were written by a model reading each function's "
                        "normalised body in batches. In a 10-function audit, 6 were right, 1 was incomplete and 3 "
                        "carried a wrong specific detail (a count, a polarity or an offset, sometimes borrowed from "
                        "a callee). The tag records what the reader relied on (C a string or a named callee, I the "
                        "operations, H a guess), not whether the row was checked. Read the body before relying on a "
                        "detail: `python -I tools/map_find.py fn 0xADDR`.", ""]
    groups = defaultdict(list)
    for r in read:
        groups[r["module"] + ":" + region_of(r["addr"])].append(r)
    tab = ["| Page | Functions | Range |", "|---|---|---|"]
    for key in sorted(groups):
        mod, letter = key.split(":")
        rs = groups[key]
        parts = [rs[i:i + limit] for i in range(0, len(rs), limit)]
        for n, chunk in enumerate(parts, 1):
            name = f"Read-{letter}" if len(parts) == 1 else f"Read-{letter}-{n}"
            tc = Counter(r["tag"] for r in chunk)
            pages[name] = "\n".join([
                f"Region {letter}, part {n} of {len(parts)}: {len(chunk):,} functions read from their own code "
                f"({tc['C']:,} confirmed by a string or a named callee, {tc['I']:,} inferred from the operations, "
                f"{tc['H']:,} guesses). The roles are unverified; the audit is on "
                f"[Read roles](Read-roles).",
                "",
                "Rows are in address order, folded in 256 KB bands. The columns are the address, the role in plain "
                "words, and the tag that records what the reader relied on.",
                "",
                banded(["Address", "Role", "Tag"], [[r["addr"], known_code(r["role"], r.get("strings")), r["tag"]]
                                                   for r in chunk]), "",
            ])
        tab.append(f"| [{'Read ' + letter}](Read-{letter}{'' if len(parts) == 1 else '-1'}) | {len(rs):,} | "
                   f"{hex(int(rs[0]['addr'], 16))} to {hex(int(rs[-1]['addr'], 16))} |")
        if len(parts) > 1:
            for n in range(2, len(parts) + 1):
                tab.append(f"| [Read {letter} part {n}](Read-{letter}-{n}) | {len(parts[n-1])} | "
                           f"{hex(int(parts[n-1][0]['addr'], 16))} to {hex(int(parts[n-1][-1]['addr'], 16))} |")
    index += tab
    pages["Read-roles"] = "\n".join(index)
    return pages


